"""Детерминированная обработка свободного текста воронки.

Здесь ВСЕ правила собраны явно, чтобы их можно было глазами проверить и дополнить:
  * STOP_TEMPLATES        — шаблонные/системные ответы, которые НЕ отправляем в LLM
  * OUTFLOW_REASON_RULES  — причина оттока из ЧЕК-ЛИСТА (задачи типа «Отток»)
  * KEYWORD_RULES         — частые формулировки -> причина/действие без LLM

Идея: чем больше решается здесь, тем меньше строк уходит в LLM.
"""
from __future__ import annotations

import re

# --------------------------------------------------------------------------- #
# 1. Шаблонные ответы. Ключ — нормализованный текст (lower, без пунктуации по краям).
#    Значение — пояснение, ПОЧЕМУ это шаблон (видно в логах при show_llm).
# --------------------------------------------------------------------------- #
STOP_TEMPLATES: dict[str, str] = {
    # --- системные коды АС (проставляются автоматически) ---
    "accomplished": "системный код АС",
    "not_accomplished": "системный код АС",
    "change_the_payment_date": "системный код АС",
    "done": "системный код АС",
    "ok": "системный код АС",
    # --- дежурные формулировки сотрудников (не несут причины) ---
    "провела работу": "дежурная формулировка",
    "провел работу": "дежурная формулировка",
    "проведена работа": "дежурная формулировка",
    "работа проведена": "дежурная формулировка",
    "выполнено": "дежурная формулировка",
    "отработано": "дежурная формулировка",
    "обработано": "дежурная формулировка",
    "согласен": "односложный ответ",
    "согласна": "односложный ответ",
    "да": "односложный ответ",
    "нет": "односложный ответ",
    "без комментариев": "пустой по смыслу",
    "нет комментариев": "пустой по смыслу",
    "комментарий отсутствует": "пустой по смыслу",
    # --- заглушки чек-листов ---
    "пункт не актуален": "заглушка чек-листа",
    "не актуально": "заглушка чек-листа",
    "не требуется": "заглушка чек-листа",
    "-": "пустой по смыслу",
    "—": "пустой по смыслу",
}

# Короче этого (после нормализации) считаем неинформативным
MIN_MEANINGFUL_LEN = 15


def _norm(text: str | None) -> str:
    """Нормализация для сравнения с шаблонами."""
    if not text:
        return ""
    t = str(text).replace("<br>", " ").strip().lower()
    t = re.sub(r"\s+", " ", t)
    return t.strip(" .;:!?\t\n\r")


def is_meaningful(text: str | None) -> tuple[bool, str]:
    """Стоит ли отправлять этот текст в LLM. Возвращает (решение, причина).

    Причина печатается в логах — видно, какой именно шаблон сработал.
    """
    n = _norm(text)
    if not n:
        return False, "пусто"
    if n in STOP_TEMPLATES:
        return False, f"шаблон «{n}» ({STOP_TEMPLATES[n]})"
    if len(n) < MIN_MEANINGFUL_LEN:
        return False, f"слишком коротко ({len(n)} симв. < {MIN_MEANINGFUL_LEN})"
    return True, "ок"


# --------------------------------------------------------------------------- #
# 2. Чек-лист (task_questionnaire). Формат АС: "1. Вопрос\nОтвет\n2. Вопрос\nОтвет"
# --------------------------------------------------------------------------- #
_Q_SPLIT = re.compile(r"(?m)^\s*\d+\.\s*")


def parse_questionnaire(text: str | None) -> dict[str, str]:
    """Разобрать чек-лист в {вопрос: ответ}. Пустой словарь, если формат не тот."""
    if not text:
        return {}
    out: dict[str, str] = {}
    for chunk in _Q_SPLIT.split(str(text)):
        chunk = chunk.strip()
        if not chunk:
            continue
        parts = chunk.split("\n", 1)
        question = parts[0].strip()
        answer = parts[1].strip() if len(parts) > 1 else ""
        if question:
            out[question] = answer
    return out


# Причина оттока из чек-листа: канонический ответ -> (причина, действие, вердикт)
# Вердикт: "no_point" — работать бессмысленно, "work" — есть смысл отрабатывать.
OUTFLOW_REASON_RULES: dict[str, tuple[str, str, str]] = {
    "ликвидация организации":
        ("Ликвидация организации", "Исключить из отработки", "no_point"),
    "смена зарплатного банка":
        ("Смена зарплатного банка", "Пересмотреть условия, точечный возврат", "work"),
    "текучка персонала":
        ("Текучка персонала", "Удержание + привлечение новых сотрудников", "work"),
    "сокращение штата":
        ("Сокращение штата у клиента", "Низкий приоритет, мониторинг", "work"),
    "недовольство условиями обслуживания":
        ("Недовольство условиями", "Отработать возражения, улучшить сервис", "work"),
    "переход сотрудников на самозанятость":
        ("Переход на самозанятость", "Предложить продукты для самозанятых", "work"),
    "сезонные отпуска":
        ("Сезонный отток (отпуска)", "Мониторинг, возврат после сезона", "work"),
}

# Как называется вопрос про причину оттока в чек-листе (ищем по вхождению)
OUTFLOW_QUESTION_HINTS = ("причина оттока", "причина снижения", "причина ухода")


def outflow_reason(questionnaire: str | None) -> dict | None:
    """Детерминированная причина оттока ИЗ ЧЕК-ЛИСТА (задачи типа «Отток»).

    Возвращает {"reason","action","verdict","source"} или None, если в чек-листе
    вопроса про причину нет / ответ — заглушка.
    """
    qa = parse_questionnaire(questionnaire)
    if not qa:
        return None
    for question, answer in qa.items():
        if not any(h in question.lower() for h in OUTFLOW_QUESTION_HINTS):
            continue
        ans = _norm(answer)
        if not ans or ans in STOP_TEMPLATES:
            return None
        rule = OUTFLOW_REASON_RULES.get(ans)
        if rule:
            reason, action, verdict = rule
            return {"reason": reason, "action": action, "verdict": verdict,
                    "source": "чек-лист: причина оттока"}
        # причина есть, но её нет в справочнике — берём как есть, работать можно
        return {"reason": answer.strip()[:80], "action": "Отработать причину оттока",
                "verdict": "work", "source": "чек-лист: причина оттока (свободная)"}
    return None


# --------------------------------------------------------------------------- #
# 3. Ключевые слова в комментариях -> причина/действие без LLM.
#    Порядок важен: срабатывает ПЕРВОЕ совпадение.
# --------------------------------------------------------------------------- #
KEYWORD_RULES: list[tuple[tuple[str, ...], str, str, str]] = [
    # (паттерны, причина, действие, вердикт)
    (("ликвидац", "банкротств", "прекратил деятельность"),
     "Организация ликвидируется", "Исключить из отработки", "no_point"),
    (("другой банк", "сменил банк", "сменили банк", "ушли в втб", "ушли в альфа"),
     "Ушли в другой банк", "Пересмотреть условия, точечный возврат", "work"),
    (("не дозвонил", "не отвечает", "нет контакта", "недоступен"),
     "Не дозвонились до клиента", "Повторить контакт по другим каналам", "work"),
    (("повторная встреча", "нужна встреча", "назначить встречу", "встреча с директором"),
     "Нужна встреча с ЛПР", "Назначить встречу", "work"),
    (("бухгалтер против", "бухгалтер отказ", "против смены реквизитов"),
     "Возражение бухгалтерии", "Переговоры с бухгалтерией", "work"),
    (("не заинтересован", "отказался", "отказ клиента"),
     "ЛПР не заинтересован", "Сменить аргументацию/предложение", "work"),
    (("текучк",),
     "Текучка персонала", "Удержание + привлечение новых", "work"),
    (("сокращен",),
     "Сокращение штата у клиента", "Низкий приоритет, мониторинг", "work"),
    (("отпуск", "сезонн"),
     "Сезонный фактор", "Мониторинг, возврат после сезона", "work"),
    (("пауз", "отложил", "взял время", "рассматрива"),   # «паузу», «на паузе»
     "Клиент взял паузу", "Вернуться в согласованный срок", "work"),
    (("получено согласие", "клиент согласился", "согласие на перевод"),
     "Получено согласие", "Довести до зачислений", "work"),
    (("расширени",),
     "Планируется расширение", "Сопровождать расширение", "work"),
]


def match_keyword(text: str | None) -> dict | None:
    """Первое сработавшее правило по ключевым словам или None."""
    n = _norm(text)
    if not n:
        return None
    for patterns, reason, action, verdict in KEYWORD_RULES:
        if any(p in n for p in patterns):
            return {"reason": reason, "action": action, "verdict": verdict,
                    "source": "ключевые слова"}
    return None


def themes(texts: list[str]) -> str:
    """Частые причины по набору текстов (для нарратива) — на тех же правилах."""
    counts: dict[str, int] = {}
    for t in texts:
        m = match_keyword(t)
        if m:
            counts[m["reason"]] = counts.get(m["reason"], 0) + 1
    if not counts:
        return "—"
    top = sorted(counts.items(), key=lambda x: -x[1])[:4]
    return ", ".join(f"{name} ({n})" for name, n in top)
