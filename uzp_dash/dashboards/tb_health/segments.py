"""Хардкод-маппинг сегментов УЗП (uzp_dwh_metrics.extended_dim_1).

Короткие названия — основные во всём отчёте. Организации из uzp_dim_company
приходят с БОЛЬШИМ именем сегмента и подтягиваются к короткому коду.
Некоторые коды объединяют несколько больших сегментов.
"""

# extended_dim_1 -> короткое имя
SHORT = {1: "Все", 21: "КСБ", 22: "РГС", 23: "СКМ", 24: "КФИ", 25: "БМО", 1092: "ММБ"}

# расшифровка кода (для подсказок/тултипов)
FULL = {
    1: "Все сегменты",
    21: "КСБ · Средние + Крупные",
    22: "РГС · Рег. госсектор",
    23: "СКМ · Клиенты машиностроения",
    24: "КФИ · Фин.институты",
    25: "БМО · SBI",
    1092: "ММБ · Микро + Малые",
}

# большое имя сегмента (uzp_dim_company.segment_name) -> код extended_dim_1
BIG_TO_CODE = {
    "Средние": 21, "Крупные": 21, "Крупнейшие": 21,
    "Рег. госсектор": 22,
    "Клиенты машиностроения": 23,
    "Фин.институты": 24,
    "SBI": 25,
    "Микро": 1092, "Малые": 1092,
}

# порядок коротких сегментов в отчёте
ORDER = ["КСБ", "РГС", "СКМ", "КФИ", "БМО", "ММБ"]


def short(code) -> str:
    try:
        return SHORT.get(int(code), str(code))
    except (TypeError, ValueError):
        return "—"


def code_of_big(name):
    return BIG_TO_CODE.get(name)


def short_of_big(name):
    c = BIG_TO_CODE.get(name)
    return SHORT.get(c) if c is not None else None
