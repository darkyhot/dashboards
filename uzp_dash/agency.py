def _compile(words: tuple[str, ...]) -> re.Pattern:
    """Слова-признаки в одну регулярку с границами слова.

    Границы обязательны: без них «ДК» нашлось бы внутри «ДКБ», «СУД» внутри
    «СУДОРЕМОНТНЫЙ», а «ИК» — вообще где угодно. Стандартный \\b с кириллицей в
    Python работает (re.UNICODE по умолчанию), но дефис он считает границей, а
    нам нужно, чтобы «ШКОЛА-ИНТЕРНАТ» не разбивалось на два признака, — поэтому
    границы заданы явно через отрицательные проверки по буквам и цифрам.
    """
    parts = [re.escape(w) for w in sorted(words, key=len, reverse=True)]
    body = "|".join(parts)
    return re.compile(rf"(?<![А-ЯЁA-Z0-9])(?:{body})(?![А-ЯЁA-Z0-9])")


_PATTERNS: list[tuple[str, re.Pattern]] = [(k, _compile(w)) for k, w in RULES]

# Наименование нормализуется перед разбором: регистр, «ё», кавычки и лишние
# пробелы приходят из витрины в любом виде.
_NORM = re.compile(r"[\"'«»№.,()]+")


def normalize(name) -> str:
    if name is None or (isinstance(name, float) and pd.isna(name)):
        return ""
    s = str(name).upper().replace("Ё", "Е")
    s = _NORM.sub(" ", s)
    return re.sub(r"\s+", " ", s).strip()


def classify(name, is_force=None, industry_name=None) -> str:
    """Ведомство по наименованию. Возвращает человекочитаемое имя или UNKNOWN.

    `is_force` — флаг силовой организации из витрины оттока. Он ПЕРЕВЕШИВАЕТ
    разбор имени: витрина знает про организацию больше, чем её вывеска, и
    «ФКУ № 12» без слова-признака иначе ушло бы в «не классифицировано».
    """
    if is_force is True:
        return AGENCIES["security"]
    text = normalize(name)
    if text:
        for key, pattern in _PATTERNS:
            if pattern.search(text):
                return AGENCIES[key]
    hint = INDUSTRY_HINTS.get(str(industry_name or "").strip())
    if hint:
        return AGENCIES[hint]
    return UNKNOWN


def classify_frame(df: pd.DataFrame, name_col: str = "company_name",
                   force_col: str = "is_force",
                   industry_col: str = "industry_name") -> pd.Series:
    """Ведомство для каждой строки. Отсутствующие колонки — не ошибка.

    Отсутствующая колонка через `df.get()` вернула бы СКАЛЯР nan, и следующая
    операция упала бы уже где-то дальше по коду (ловушка 1 из правил). Поэтому
    каждая колонка приводится к Series явно.
    """
    n = len(df)
    names = df[name_col] if name_col in df else pd.Series([None] * n, index=df.index)
    force = df[force_col] if force_col in df else pd.Series([None] * n, index=df.index)
    ind = df[industry_col] if industry_col in df else pd.Series([None] * n, index=df.index)
    return pd.Series(
        [classify(nm, f if f in (True, False) else None, ig)
         for nm, f, ig in zip(names, force, ind)],
        index=df.index, name="agency")


def coverage(agencies: pd.Series) -> tuple[int, int, float]:
    """Сколько строк классифицировано: (разобрано, всего, доля)."""
    total = int(len(agencies))
    known = int((agencies != UNKNOWN).sum())
    return known, total, (known / total if total else 0.0)
