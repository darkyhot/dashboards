"""Промпты разделов. Только сборка текста запроса — ни одного вызова модели.

Три правила, общие для всех промптов файла:

1. **В модель уходят ЦИФРЫ, а не выводы.** Просить «объясни падение» бессмысленно:
   модель не видит данных и сочинит правдоподобное. Ей даётся посчитанная
   раскладка, а её работа — назвать главное словами.
2. **Названий организаций, холдингов, ГОСБ и регионов в промпте нет.** Вместо них
   токены (`Орг-01`), которые возвращаются на место уже в ответе. Корпоративный
   шлюз блокирует запрос с чувствительным названием и отправляет обращение в
   blacklist — узнать об этом на проме дорого.
3. **Модели запрещено додумывать причины.** Она пересказывает раскладку, а не
   строит гипотезы: гипотеза, поданная тем же тоном, что и расчёт, неотличима от
   расчёта, и проверять её читатель не станет.
"""
from __future__ import annotations

import pandas as pd

RULES = (
    "Пиши по-русски, деловым тоном, без вводных слов и без списков. "
    "Три-четыре предложения. Не придумывай причин, которых нет в данных: "
    "твоя задача — назвать словами то, что уже посчитано. "
    "Не используй слово «ИНН». Названия из данных, если они есть, приводи "
    "ровно так, как они написаны."
)


# Как называются колонки В ПРОМПТЕ. Модель пересказывает заголовки таблицы
# буквально, и с техническими именами вывод получается на смеси языков:
# «преобладает real при 1242 method». Русские заголовки стоят ровно столько же,
# а текст выходит читаемым.
COL_NAMES = {
    "n_triples": "получателей", "n_epk": "человек", "share": "доля",
    "kind": "вид", "title": "причина", "real": "настоящая_потеря",
    "method": "особенности_счёта", "gap": "перерыв",
    "report_dt": "месяц", "n_alive": "живо", "delta": "изменение",
    "score": "во_сколько_раз_резче", "threshold": "порог",
    "base": "было", "cur": "стало", "delta_pct": "изменение_проц",
    "epk_base": "человек_было", "epk_cur": "человек_стало",
    "d_epk": "изменение_человек", "d_epk_pct": "изменение_проц",
    "code": "код", "code_name": "вид_зачисления",
    "in_list": "входит_в_метрику", "multi": "получателей_на_человека",
    "yoy": "год_к_году", "yoy_epk": "год_к_году_человек",
    "name_from": "откуда", "name_to": "куда", "n_inn": "организаций",
}


def _tbl(df: pd.DataFrame, cols: list[str], limit: int = 10) -> str:
    """Кадр в текст для промпта. Только нужные колонки, только верх, по-русски."""
    if df is None or df.empty:
        return "(данных нет)"
    use = [c for c in cols if c in df.columns]
    if not use:
        return "(данных нет)"
    out = df[use].head(limit).rename(columns=COL_NAMES)
    return out.to_string(index=False)


def overview(base_m: str, cur_m: str, t: dict, causes, causes_epk) -> str:
    """Главный вывод: сколько из падения реально, а сколько — счёт."""
    return f"""Численность зарплатного сегмента бюджетной сферы считается
получателями — тройками (человек, организация, подразделение банка): один
человек может весить нескольких получателей.

Было в {base_m}: {t['triples_base']:,.0f} получателей ({t['epk_base']:,.0f} человек).
Стало в {cur_m}: {t['triples_cur']:,.0f} получателей ({t['epk_cur']:,.0f} человек).
Изменение: {t['d_triples']:,.0f} получателей и {t['d_epk']:,.0f} человек.

Падение метрики раскладывается на два разных вклада:
- людей стало меньше: {t['d_by_people']:,.0f} получателей;
- совместительство схлопнулось: {t['d_by_multi']:,.0f}. Доля совместителей
  изменилась с {t['multi_share_base']:.2%} до {t['multi_share_cur']:.2%}.

Раскладка потерь по причинам (получатели):
{_tbl(causes, ['title', 'kind', 'n_triples', 'share'], 12)}

Та же раскладка по ЛЮДЯМ (веток меньше: перевод, совместительство и переход
внутри сегмента человека не убавляют):
{_tbl(causes_epk, ['title', 'kind', 'n_epk', 'share'], 12)}

{RULES}
Скажи главное: насколько падение — это ушедшие люди, а насколько — счёт.
Обязательно сравни две раскладки между собой."""


def net(base_m: str, cur_m: str, t: dict, gains) -> str:
    """Выросли или нет, если не брать методологию счёта."""
    return f"""Движение получателей с {base_m} по {cur_m} разложено на три вида,
причём И потери, И приход:

- реальное движение: {t['net_real']:,.0f} получателей ({t['net_real_epk']:,.0f} человек)
  — новые люди и организации минус ушедшие из банка и из сегмента;
- особенности счёта: {t['net_method']:,.0f} ({t['net_method_epk']:,.0f} человек)
  — порог, коды, переводы между подразделениями, совместительство, переходы
  внутри сегмента; людей не прибавляют и не убавляют;
- перерывы в выплатах: {t['net_gap']:,.0f} ({t['net_gap_epk']:,.0f} человек)
  — человека нет в отчётном месяце, но в предыдущие он был.

Сумма трёх видов равна общему изменению: {t['d_triples']:,.0f} получателей.

Из чего состоит приход:
{_tbl(gains, ['title', 'kind', 'n_triples', 'share'], 10)}

{RULES}
Ответь прямо: вырос сегмент или нет, если смотреть только на реальное движение.
Не называй ростом то, что относится к счёту или к перерывам."""


def when(cur_m: str, tr, st, measured: str, cmp_months, surv) -> str:
    """Когда: ступень, сезон или текучесть."""
    steps_txt = (_tbl(st, ["report_dt", "delta", "score"], 6)
                 if st is not None and not st.empty
                 else "(месяцев-обрывов не найдено, изменение идёт плавно)")
    return f"""Отчётный месяц против соседних и против того же месяца год назад:
{_tbl(cmp_months, ['report_dt', 'n_triples', 'n_epk', 'multi'], 8)}

Помесячный ряд (yoy — изменение к тому же месяцу год назад):
{_tbl(tr, ['report_dt', 'n_triples', 'n_epk', 'yoy', 'yoy_epk'], 30)}

Месяцы, где изменение резко выпадает из обычного. Мерилось: {measured}.
{steps_txt}

Дожитие получателей базового месяца:
{_tbl(surv, ['report_dt', 'n_alive', 'share'], 30)}

{RULES}
Скажи, когда произошло падение и не является ли отчётный месяц сезонной ямой.
Если отчётный месяц ниже соседних примерно так же, как был ниже год назад, — это
сезон, и годовое падение из него выводить нельзя. Регулярный провал, который
повторяется каждый год, событием не является."""


def why(thr, split, gone, mig) -> str:
    """Почему: порог, коды, переоформление."""
    return f"""Проверены три возможных объяснения падения.

1. Порог получателя. Численность при разных порогах:
{_tbl(thr, ['threshold', 'base', 'cur', 'delta', 'delta_pct'], 8)}

2. Коды видов зачисления, СГРУППИРОВАННЫЕ на две части:
{_tbl(split, ['title', 'epk_base', 'epk_cur', 'd_epk', 'd_epk_pct'], 4)}

Коды, исчезнувшие из витрины целиком (колонка in_list — входит ли код в метрику):
{_tbl(gone, ['code', 'code_name', 'base', 'in_list'], 10)}

3. Организации, чьи люди дружно перешли в один и тот же новый номер —
признак переоформления, а не оттока (названия заменены токенами):
{_tbl(mig, ['name_from', 'name_to', 'n_epk', 'share'], 10)}

{RULES}

ОСОБО ВАЖНО про коды. Метрика считает ТОЛЬКО коды из списка. Код, которого в
списке нет, не влияет на неё НИ ПРИ КАКОМ своём поведении — даже если он
обнулился полностью. Не пиши, что падение вызвано изменением кодов вне списка:
это неверно по построению метрики, а не по обстоятельствам. Про такие коды можно
сказать только, что в витрине произошла перемена, к метрике не относящаяся.

Скажи, какое из трёх объяснений подтвердилось, а какое нет. Если падение
сохраняется при нулевом пороге, порог ни при чём."""


def where(cuts: dict) -> str:
    """Где: разрезы с составом по видам. Названия — токенами."""
    blocks = []
    titles = {"holding_name": "Холдинги", "agency": "Ведомства",
              "level": "Уровень подчинения", "tb_short_name": "Территориальные банки",
              "region_name": "Регионы"}
    for dim, df in cuts.items():
        if df is None or df.empty:
            continue
        blocks.append(f"{titles.get(dim, dim)}:\n"
                      + _tbl(df, [dim, "n_triples", "share", "real", "method", "gap"], 8))
    body = "\n\n".join(blocks) or "(разрезы не построились)"
    return f"""Потери получателей в разрезах. Колонки: real — настоящая потеря
(люди ушли), method — особенности счёта (люди на месте), gap — перерыв в
выплатах. Названия заменены токенами.

{body}

{RULES}
Скажи, где сосредоточена потеря и одинаков ли её характер: где это ушедшие люди,
а где — особенности счёта."""
