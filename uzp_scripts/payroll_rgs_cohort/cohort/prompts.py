"""Промпты разделов. Только сборка текста запроса — ни одного вызова модели.

Три правила, общие для всех промптов файла:

1. **В модель уходят ЦИФРЫ, а не выводы.** Просить «объясни падение» бессмысленно:
   модель не видит данных и сочинит правдоподобное. Ей даётся посчитанная
   раскладка, а её работа — назвать главное словами.
2. **Названий организаций, холдингов, ГОСБ и регионов в промпте нет.** Вместо них
   токены (`Орг-01`), которые возвращаются на место уже в ответе. Корпоративный
   шлюз блокирует запрос с чувствительным названием и отправляет обращение в
   blacklist — узнать об этом на проме дорого.
3. **Модели запрещено додумывать причины.** Она пересказывает раскладку, а не
   строит гипотезы: гипотеза, поданная тем же тоном, что и расчёт, неотличима от
   расчёта, и проверять её читатель не станет.
"""
from __future__ import annotations

import pandas as pd

RULES = (
    "Пиши по-русски, деловым тоном, без вводных слов и без списков. "
    "Три-четыре предложения. Не придумывай причин, которых нет в данных: "
    "твоя задача — назвать словами то, что уже посчитано. "
    "Не используй слово «ИНН». Названия из данных, если они есть, приводи "
    "ровно так, как они написаны."
)


def _tbl(df: pd.DataFrame, cols: list[str], limit: int = 10) -> str:
    """Кадр в текст для промпта. Только нужные колонки и только верх."""
    if df is None or df.empty:
        return "(данных нет)"
    use = [c for c in cols if c in df.columns]
    if not use:
        return "(данных нет)"
    return df[use].head(limit).to_string(index=False)


def overview(base_m: str, cur_m: str, t: dict, causes: pd.DataFrame) -> str:
    """Главный вывод: сколько из падения реально, а сколько — счёт."""
    return f"""Численность зарплатного сегмента бюджетной сферы считается парами
(человек, организация): совместитель весит двух получателей.

Было в {base_m}: {t['pairs_base']:,.0f} пар ({t['epk_base']:,.0f} человек).
Стало в {cur_m}: {t['pairs_cur']:,.0f} пар ({t['epk_cur']:,.0f} человек).
Изменение: {t['d_pairs']:,.0f} пар.

Падение раскладывается на два разных вклада:
- людей стало меньше: {t['d_by_people']:,.0f} пар;
- совместительство схлопнулось (у людей стало меньше организаций):
  {t['d_by_multi']:,.0f} пар. Доля совместителей изменилась с
  {t['multi_share_base']:.2%} до {t['multi_share_cur']:.2%}.

Потеряно пар всего: {t['lost']:,.0f}, пришло: {t['gained']:,.0f}.
Из потерянных {t['lost_not_real']:,.0f} — не ушедшие люди, а особенности счёта.

Раскладка потерь по причинам:
{_tbl(causes, ['title', 'n_pairs', 'share'], 10)}

{RULES}
Скажи главное: насколько падение — это ушедшие люди, а насколько — счёт."""


def when(cur_m: str, tr: pd.DataFrame, st: pd.DataFrame,
         surv: pd.DataFrame) -> str:
    """Когда: ступень или текучесть."""
    steps_txt = (_tbl(st, ["report_dt", "d_pairs", "d_pairs_pct", "score"], 6)
                 if st is not None and not st.empty
                 else "(месяцев-обрывов не найдено, снижение идёт плавно)")
    return f"""Помесячный ряд получателей бюджетной сферы (пары человек-организация):
{_tbl(tr, ['report_dt', 'n_pairs', 'n_epk', 'd_pairs'], 30)}

Месяцы, где изменение резко выпадает из обычного шага ряда:
{steps_txt}

Дожитие пар базового месяца:
{_tbl(surv, ['report_dt', 'n_alive', 'share'], 30)}

{RULES}
Скажи, когда произошло падение: одним месяцем-ступенью или равномерно за год.
Если ступени есть, назови месяцы. Обрыв в одном месяце означает событие
(смена кодировки выплат, переклассификация, загрузка данных), плавное
снижение — текучесть."""


def why(thr: pd.DataFrame, codes: pd.DataFrame, mig: pd.DataFrame) -> str:
    """Почему: порог, коды, реорганизация."""
    return f"""Проверены три возможных объяснения падения.

1. Порог получателя (сумма зачислений за месяц). Как выглядит численность при
разных порогах:
{_tbl(thr, ['threshold', 'base', 'cur', 'delta', 'delta_pct'], 8)}

2. Коды видов зачисления: сколько человек получали по каждому коду в базовом и
отчётном месяце. «Вне списка» — коды, которые метрика не считает:
{_tbl(codes, ['code', 'code_name', 'in_list', 'base', 'cur', 'delta'], 12)}

3. Организации, чьи люди дружно перешли в один и тот же новый номер —
признак переоформления, а не оттока (названия заменены токенами):
{_tbl(mig, ['name_from', 'name_to', 'n_epk', 'share'], 10)}

{RULES}
Скажи, какое из трёх объяснений подтвердилось, а какое нет. Если падение
сохраняется при нулевом пороге, порог ни при чём."""


def where(cuts: dict) -> str:
    """Где: разрезы с составом причин. Названия — токенами."""
    blocks = []
    titles = {"holding_name": "Холдинги", "agency": "Ведомства",
              "level": "Уровень подчинения", "tb_short_name": "Территориальные банки",
              "region_name": "Регионы"}
    for dim, df in cuts.items():
        if df is None or df.empty:
            continue
        blocks.append(f"{titles.get(dim, dim)}:\n"
                      + _tbl(df, [dim, "n_pairs", "share", "real_loss", "not_real"], 8))
    body = "\n\n".join(blocks) or "(разрезы не построились)"
    return f"""Потери получателей в разрезах. Колонка real_loss — потери, которые
являются оттоком людей; not_real — то, что оттоком не является (сумма ниже
порога, код вне списка, схлопнувшееся совместительство, переход внутри
сегмента). Названия заменены токенами.

{body}

{RULES}
Скажи, где сосредоточена потеря и одинаков ли её характер: где это ушедшие
люди, а где — особенности счёта."""
