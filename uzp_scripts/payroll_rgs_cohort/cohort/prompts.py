def _tbl(df: pd.DataFrame, cols: list[str], limit: int = 10) -> str:
    """Кадр в текст для промпта. Только нужные колонки, только верх, по-русски."""
    if df is None or df.empty:
        return "(данных нет)"
    use = [c for c in cols if c in df.columns]
    if not use:
        return "(данных нет)"
    out = df[use].head(limit).rename(columns=COL_NAMES)
    return out.to_string(index=False)


def _decomp_txt(t: dict) -> str:
    """Единственное разложение изменения — те же строки, что в отчёте."""
    from .analyze import decomposition
    return "\n".join(f"{r['sign']} {r['title']}: {r['triples']:,.0f} получателей, "
                     f"{r['epk']:,.0f} ФЛ".strip() for r in decomposition(t))


