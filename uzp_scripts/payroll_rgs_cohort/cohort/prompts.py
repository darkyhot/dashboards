def where(cuts: dict) -> str:
    """Где: разрезы. Названия — токенами."""
    blocks = []
    titles = {"holding_name": "Холдинги", "agency": "Ведомства",
              "level": "Уровень подчинения", "tb_short_name": "Территориальные банки",
              "gosb_name": "ГОСБы"}
    for dim, df in cuts.items():
        if df is None or df.empty:
            continue
        blocks.append(f"{titles.get(dim, dim)}:\n"
                      + _tbl(df, [dim, "loss", "share", "left_bank", "left_segment",
                                  "other_codes", "below_threshold", "gained_real",
                                  "moves", "delta"], 16))
    body = "\n\n".join(blocks) or "(разрезы не построились)"
    return f"""Получатели, переставшие получать зарплату в РГС, в разрезах.
«Перестали_получать» — сумма четырёх ситуаций: нет зачислений в банке, зарплата
от небюджетной организации, только незарплатные выплаты, зарплата до 2 500 ₽. Доля —
от всех переставших. Названия заменены токенами.

{body}

{RULES}
{VOCAB}
Скажи, где больше всего перестали получать зарплату в РГС и одинаков ли состав
ситуаций."""


