"""Уровень подчинения организации: федеральный / региональный / муниципальный.

Отдельного поля в разрешённых источниках нет, поэтому уровень выводится из
организационно-правовой формы в наименовании — из тех самых префиксов, которые
её и кодируют: ФГБОУ → федеральное, ГБОУ → региональное, МБОУ → муниципальное.

Две вещи, без которых классификатор молча врёт:

1. **Порядок значим, но одного порядка мало.** «ФГБОУ» содержит «ГБОУ» как
   подстроку, и разбор подстрокой отнёс бы федеральный вуз к региональным. Спасает
   не порядок, а поиск по ЦЕЛЫМ СЛОВАМ — тот же `_compile`, что у классификатора
   ведомств: «ГБОУ» внутри «ФГБОУ» словом не является. Порядок оставлен
   федеральный→региональный→муниципальный только ради читаемости правил.
2. **Неразобранное имя не раскидывается по уровням.** Оно идёт в «Не
   классифицировано» отдельной строкой. Приписать его к массовому уровню значило
   бы завысить потерю этого уровня на неизвестную величину — а весь разбор
   затевался ровно затем, чтобы такие приписки убрать.

Флаги справочника ЕПК (`is_military`, `is_educational`) уровень НЕ определяют:
военкомат бывает и федеральным, и муниципальным, а школа — и той и другой.
"""
from __future__ import annotations

import pandas as pd

from uzp_dash.agency import _compile, normalize  # noqa: SLF001 — одни правила на проект

FEDERAL = "Федеральное"
REGIONAL = "Региональное"
MUNICIPAL = "Муниципальное"
COMMERCIAL = "Коммерция"
UNKNOWN = "Не классифицировано"

ORDER = [FEDERAL, REGIONAL, MUNICIPAL, COMMERCIAL, UNKNOWN]

# Порядок правил — сверху вниз, побеждает первое совпавшее.
RULES: list[tuple[str, tuple[str, ...]]] = [
    # Федеральные. Сюда же силовые и фискальные: они федеральны по определению,
    # и без них МВД с УФНС ушли бы в «не классифицировано» — у них нет привычного
    # префикса организационно-правовой формы.
    (FEDERAL, ("ФГБОУ", "ФГАОУ", "ФГКОУ", "ФГБУ", "ФГАУ", "ФГКУ", "ФКУ", "ФБУ",
               "ФГУП", "ФКП", "ФГБУЗ", "ФГБНУ", "ФЕДЕРАЛЬНОЕ", "ФЕДЕРАЛЬНАЯ",
               "ФЕДЕРАЛЬНЫЙ", "МВД", "УМВД", "ГУМВД", "ОМВД", "МЧС", "ФСБ",
               "ФСИН", "УФСИН", "РОСГВАРДИЯ", "РОСГВАРДИИ", "ФНС", "УФНС", "ИФНС",
               "УФК", "КАЗНАЧЕЙСТВО", "КАЗНАЧЕЙСТВА", "ФССП", "УФССП",
               "ПРОКУРАТУРА", "ПРОКУРАТУРЫ", "ВОЙСКОВАЯ", "МИНОБОРОНЫ")),
    # Региональные — субъекта РФ. Префикс «Г» без «Ф» и «М»: ГБОУ, ГБУЗ, ГКУ.
    # «ОГБУ»/«КГБУ»/«ГАУЗ» — те же формы в областном и краевом написании.
    (REGIONAL, ("ГБОУ", "ГАОУ", "ГКОУ", "ГБУ", "ГАУ", "ГКУ", "ГУП", "ГБУЗ",
                "ГАУЗ", "ГБУК", "ГБПОУ", "ГАПОУ", "ОГБУ", "ОГКУ", "ОГАУ",
                "КГБУ", "КГКУ", "КГАУ", "ГОСУДАРСТВЕННОЕ", "ГОСУДАРСТВЕННАЯ",
                "ГОСУДАРСТВЕННЫЙ", "ОБЛАСТНОЕ", "ОБЛАСТНАЯ", "ОБЛАСТНОЙ",
                "КРАЕВОЕ", "КРАЕВАЯ", "КРАЕВОЙ", "РЕСПУБЛИКАНСКОЕ",
                "РЕСПУБЛИКАНСКАЯ", "МИНИСТЕРСТВО", "МИНИСТЕРСТВА")),
    # Муниципальные. «МБУЗ»/«МБДОУ»/«МУП» и словесная форма.
    (MUNICIPAL, ("МБОУ", "МАОУ", "МКОУ", "МБДОУ", "МАДОУ", "МКДОУ", "МБУ", "МАУ",
                 "МКУ", "МУП", "МБУЗ", "МБУК", "МАУК", "МБУДО", "МКУК",
                 "МУНИЦИПАЛЬНОЕ", "МУНИЦИПАЛЬНАЯ", "МУНИЦИПАЛЬНЫЙ",
                 "АДМИНИСТРАЦИЯ", "АДМИНИСТРАЦИИ", "МЭРИЯ",
                 "СОВЕТ ДЕПУТАТОВ", "ГОРОДСКОГО ОКРУГА", "СЕЛЬСКОГО ПОСЕЛЕНИЯ")),
    # Коммерческие формы. В бюджетном сегменте их быть не должно — если их много,
    # это сигнал о разметке сегмента, и отчёт обязан его показать, а не спрятать.
    (COMMERCIAL, ("ООО", "АО", "ПАО", "ЗАО", "ОАО", "НАО", "ИП", "АНО", "НКО")),
]

_PATTERNS: list[tuple[str, object]] = [(k, _compile(w)) for k, w in RULES]


def classify(name) -> str:
    """Уровень подчинения по наименованию. Возвращает уровень или UNKNOWN."""
    text = normalize(name)
    if not text:
        return UNKNOWN
    for level, pattern in _PATTERNS:
        if pattern.search(text):
            return level
    return UNKNOWN


def classify_frame(df: pd.DataFrame, name_col: str = "company_name") -> pd.Series:
    """Уровень для каждой строки. Отсутствующая колонка — не ошибка.

    Через `df.get()` отсутствующая колонка вернула бы СКАЛЯР nan, и падение
    случилось бы где-то дальше по коду (ловушка 1 правил платформы). Поэтому
    колонка приводится к Series явно.
    """
    names = (df[name_col] if name_col in df
             else pd.Series([None] * len(df), index=df.index))
    return pd.Series([classify(n) for n in names], index=df.index, name="level")


def coverage(levels: pd.Series) -> tuple[int, int, float]:
    """Сколько строк классифицировано: (разобрано, всего, доля)."""
    total = int(len(levels))
    known = int((levels != UNKNOWN).sum())
    return known, total, (known / total if total else 0.0)
