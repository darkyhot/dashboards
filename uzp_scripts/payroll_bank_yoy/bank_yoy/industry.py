_COMPILED = [(g, re.compile(p)) for g, p in RULES]


def norm(name) -> str:
    """Приведение регистра — то же, что `translate` в SQL."""
    return str(name).translate(_TR) if isinstance(name, str) else ""


def classify(name) -> str:
    """Python-версия правил (для самопроверок; в отчёте считает SQL)."""
    if not isinstance(name, str) or not name.strip():
        return UNKNOWN
    x = norm(name)
    for g, rx in _COMPILED:
        if rx.search(x):
            return g
    return UNKNOWN


def sql_case(col: str) -> str:
    """CASE для SQL: те же правила, тот же порядок. Значения — константы кода."""
    x = f"translate({col}, '{_LOW}', '{_UP}')"
    whens = "\n".join(f"    WHEN {x} ~ '{p}' THEN '{g}'" for g, p in RULES)
    return f"CASE\n    WHEN {col} IS NULL THEN '{UNKNOWN}'\n{whens}\n    ELSE '{UNKNOWN}'\n  END"


