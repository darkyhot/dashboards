"""Генерация блока `insert into tmp_task_tmpl` для «скоринг_new_v2.sql».

Читает «Тексты для основных задач 07.08.26 (1).xlsx» (Лист2) и печатает готовый
VALUES-список. Тексты переносятся дословно, заменяются только плейсхолдеры на
токены, которые SQL подставляет через replace().

Запуск из каталога со скриптом:
    python3 gen_task_templates.py > /tmp/tmpl.sql
и затем вставить содержимое в скрипт вместо текущего VALUES-списка.
"""
import re

import openpyxl

SRC = "Тексты для основных задач 07.08.26 (1).xlsx"

# (строка Excel, эффективная роль в БД, task_role, тип задачи)
# Строки 6-9 (ЗУпр КИБ) не переносятся — роль исключена из выгрузки.
# task_role берётся из столбца «сборка для». В исходнике одна и та же роль
# записана двумя способами — «НУ» в строке 3 (инфо) и «НУ ГОСБ» в строке 14
# (основная); приводим к единому коду «НУ ГОСБ». У «НО ЗП» расхождения нет.
ROWS = [
    (2,  "УПР",     "УПР",     "основная"),
    (3,  "УПР",     "НУ ГОСБ", "инфо"),
    (4,  "УПР",     "КМ ВКО",  "инфо"),
    (5,  "УПР",     "КМ МТ",   "инфо"),
    (10, "ЗУПР РБ", "ЗУПР РБ", "основная"),
    (11, "ЗУПР РБ", "НО ЗП",   "инфо"),
    (12, "ЗУПР РБ", "КМ ВКО",  "инфо"),
    (13, "ЗУПР РБ", "КМ МТ",   "инфо"),
    (14, "НУ ГОСБ", "НУ ГОСБ", "основная"),
    (15, "НО ЗП",   "НО ЗП",   "основная"),
    (16, "МКК ТБ",  "МКК ТБ",  "основная"),
    # закреплённая роль КМ+МЗП: задача на МЗП берёт текст строки 18,
    # задачи на КМ — текст строки 17 (так же было в предыдущем скрипте)
    (18, "КМ+МЗП",  "МЗП",     "основная"),
    (17, "КМ+МЗП",  "КМ ВКО",  "основная"),
    (17, "КМ+МЗП",  "КМ МТ",   "основная"),
    (18, "МЗП",     "МЗП",     "основная"),
]

STRAT_COL = {"привлечение": "D", "удержание": "E", "отток": "F"}

# Семейство A — «Текущий потенциал …» / «Справочно: … , Портфель … ».
# Разделительный пробел ПОСЛЕ предложения намеренно не захватывается: он остаётся
# в шаблоне, а значение токена подставляется без хвостового пробела. Если фразу
# вырезали, образуется двойной пробел — он схлопывается в самом скрипте.
FACTS_A = re.compile(
    r"(?:Текущий потенциал по данным РОССТАТ составляет \[число\] ФЛ\."
    r"|Справочно: потенциал по данным РОССТАТ составляет \[число\] ФЛ,"
    r" Портфель ФЛ в предыдущем месяце \[число\] ФЛ\.)"
)
# Семейство B — «По данным РОССТАТ потенциал …» + отдельное «Портфель ФЛ …»
FACTS_B = re.compile(
    r"По данным РОССТАТ потенциал составляет \[число\] ФЛ\."
    r"(?: Портфель ФЛ в предыдущем месяце: \[число\] ФЛ\.)?"
)
# Финальная фраза про МКК ЦА — две пунктуационные формы в исходнике
MKK_1 = "При возникновении вопросов по задаче просьба обращаться к [ФИО МКК ЦА] (Управление зарплатных проектов, ЦА)."
MKK_2 = "При возникновении вопросов по задаче просьба обращаться к [ФИО МКК ЦА], Управление зарплатных проектов (ЦА)"


def tokenize(text: str) -> str:
    text = text.replace(MKK_1, "{MKK_CA}").replace(MKK_2, "{MKK_CA2}")
    text = FACTS_A.sub("{FACTS_A}", text)
    text = FACTS_B.sub("{FACTS_B}", text)
    text = text.replace("[название]", "{COMPANY}")
    text = text.replace("[ИНН]", "{INN}")
    text = text.replace("[номер ГОСБ]", "{GOSB}")
    text = text.replace("[ссылка]", "{LINK}")
    text = re.sub(r"\[срок отработки[^\]]*\]", "{DUE}", text)
    return text.rstrip() + "{TRIGGERS}"


def main() -> None:
    ws = openpyxl.load_workbook(SRC, data_only=True)["Лист2"]
    out = []
    left = set()
    split_rows = 0
    for row, eff_role, task_role, task_type in ROWS:
        for strategy, col in STRAT_COL.items():
            raw = ws[f"{col}{row}"].value
            assert raw, f"пустая ячейка {col}{row}"
            tokenized = tokenize(str(raw))
            # Основная задача Упр отдаётся потребителю двумя полями: карточка
            # клиента в task_text, блок «Задача: …» в task_reason. Маркер ставим
            # вместо переноса строки — он и будет разделителем для split_part().
            if (eff_role, task_role) == ("УПР", "УПР"):
                tokenized, n = re.subn(r"\nЗадача:", "{SPLIT}Задача:", tokenized, count=1)
                assert n == 1, f"не найдено начало блока «Задача:» в {col}{row}"
                split_rows += 1
            assert tokenized.count("{SPLIT}") == (
                1 if (eff_role, task_role) == ("УПР", "УПР") else 0
            ), f"неверное число маркеров {{SPLIT}} в {col}{row}"
            left.update(re.findall(r"\[[^\]]*\]", tokenized))
            out.append(
                f"    -- {eff_role} -> {task_role} / {task_type} / {strategy}"
                f"   (Excel Лист2, {col}{row})\n"
                f"    ('{eff_role}', '{task_role}', '{task_type}', '{strategy}',\n"
                f"     '{tokenized.replace(chr(39), chr(39) * 2)}')"
            )
    assert not left, f"необработанные плейсхолдеры: {left}"
    assert split_rows == len(STRAT_COL), f"маркер проставлен в {split_rows} шаблонах вместо 3"
    print(",\n".join(out))


if __name__ == "__main__":
    main()
