"""Промпты. Всё, что уходит в модель, собирается ЗДЕСЬ и только здесь.

Два жёстких требования, из-за которых промпты выглядят именно так.

**Ни одного настоящего названия.** Корпоративный шлюз блокирует запрос, если в
тексте встречается чувствительное название — например отдельного региона, — и
инцидент уходит в blacklist. Поэтому подразделения, регионы и организации
подставляются токенами (`ТБ-01`, `Регион-03`), а настоящие имена возвращаются
в ответ уже на нашей стороне. Названия ВЕДОМСТВ и БАНКОВ-КОНКУРЕНТОВ токенами не
заменяются: это классы, а не идентификаторы, и без них разбор нечитаем.

**Модель не считает.** Все числа посчитаны в `analyze` и приходят в промпт
готовыми. Модель формулирует вывод по уже сосчитанному — просить её складывать
означало бы получить правдоподобно неверные цифры, которые некому проверить.
"""
from __future__ import annotations

import pandas as pd


def _sp(v, digits: int = 0) -> str:
    """Число с ПРОБЕЛОМ между разрядами. См. комментарий в `_table`."""
    try:
        return f"{float(v):,.{int(digits)}f}".replace(",", " ")
    except (TypeError, ValueError):
        return str(v)


# Общая рамка для всех разделов: что можно и чего нельзя.
_RULES = """Ты аналитик зарплатных проектов банка. Пишешь для руководителя.

Правила:
- пиши по-русски, деловым языком, без вводных оборотов и без воды;
- НЕ придумывай числа: используй только те, что даны ниже, и не пересчитывай их;
- не упоминай, что ты модель, и не описывай, что ты делаешь;
- если данных для вывода мало, так и напиши одной фразой;
- максимум {limit} предложений, без списков и заголовков."""


def _table(df: pd.DataFrame, cols: list[tuple], limit: int = 12) -> str:
    """Таблица в промпт: только нужные колонки, только верхушка.

    Формат колонки задаётся ТРЕТЬИМ элементом кортежа ('num' | 'pct'), а не
    угадывается по величине значения. Угадывание уже дало ошибку: доля оттока
    ровно 100% (1.0) печаталась как «1.0» — по величине она неотличима от
    единицы штук, — и модель читала стопроцентный отток как одного человека.
    """
    if df is None or df.empty:
        return "(нет данных)"
    rows = []
    for r in df.head(limit).itertuples():
        cells = []
        for col in cols:
            key, title = col[0], col[1]
            fmt = col[2] if len(col) > 2 else "num"
            v = getattr(r, key, None)
            if v is None or (isinstance(v, float) and pd.isna(v)):
                cells.append(f"{title}: —")
            elif fmt == "pct":
                cells.append(f"{title}: {float(v):.1%}")
            elif isinstance(v, float):
                # Разряды разделяются ПРОБЕЛОМ, а не запятой: модель повторяет
                # разделитель в ответе, и «1,502 чел.» по-русски читается как
                # полторы единицы вместо полутора тысяч.
                cells.append(f"{title}: {_sp(v, 1)}".replace(",", " "))
            else:
                cells.append(f"{title}: {v}")
        rows.append("  - " + ", ".join(cells))
    return "\n".join(rows)


def overview(month: str, total_out: float, total_kept: float, total_ret: float,
             base_fl: float, direction: dict, agencies: pd.DataFrame,
             limit: int = 4) -> str:
    """Главный вывод: где основной отток и что с ним происходит."""
    dr = (f"за последние {direction.get('window')} мес. отток "
          f"{direction.get('word')} на {abs(direction.get('rel', 0)):.0%} "
          f"относительно предыдущих {direction.get('window')}"
          if direction.get("measurable") else "динамику измерить не по чему")
    return f"""{_RULES.format(limit=limit)}

Сегмент: клиенты бюджетной сферы. Отчётный месяц: {month}.

Итоги месяца:
  - численность получателей зарплаты: {_sp(base_fl, 0)} чел.
  - ушло за месяц: {_sp(total_out, 0)} чел.
  - из них вернулось: {_sp(total_ret, 0)} чел.
  - невозвращённый отток: {_sp(total_kept, 0)} чел.
  - динамика: {dr}

Отток по ведомствам (невозвращённый):
{_table(agencies, [("agency", "ведомство"), ("out_kept", "ушло и не вернулось"),
                   ("out_rate", "доля от численности", "pct"), ("n_org", "организаций")])}

Задача: назови, где сосредоточен отток и чем выделяются ведомства-лидеры.
Различай крупный отток в абсолютных числах и высокую ДОЛЮ оттока у небольшого
ведомства — это разные проблемы."""


def territory(month: str, tb: pd.DataFrame, regions: pd.DataFrame,
              limit: int = 4) -> str:
    """Сравнение территорий. Названия уже заменены токенами вызывающим кодом."""
    return f"""{_RULES.format(limit=limit)}

Сегмент: клиенты бюджетной сферы. Отчётный месяц: {month}.

Отток по территориальным банкам:
{_table(tb, [("tb_short_name", "банк"), ("out_kept", "ушло и не вернулось"),
             ("out_rate", "доля от численности", "pct"), ("n_org", "организаций")])}

Отток по регионам:
{_table(regions, [("region_name", "регион"), ("out_kept", "ушло и не вернулось"),
                  ("out_rate", "доля от численности", "pct"), ("n_org", "организаций")])}

Задача: сравни территории. Скажи, где отток объясняется размером портфеля, а где
доля оттока аномальна для своего масштаба. Названия используй ровно в том виде,
в каком они даны."""


def causes(month: str, window: int, drop: float, staff: float, comp: float,
           by_agency: pd.DataFrame, by_region: pd.DataFrame, limit: int = 5) -> str:
    """Разбор причин: сокращение штата или уход к конкуренту."""
    return f"""{_RULES.format(limit=limit)}

Сегмент: клиенты бюджетной сферы. Отчётный месяц: {month}.

За {window} мес. численность получателей упала на {_sp(drop, 0)} чел. Падение
разложено на две причины (сумма частей равна падению):
  - сокращение штата (в организации стало меньше людей): {_sp(staff, 0)} чел.
  - уход к конкуренту (люди остались, зарплату получают не у нас): {_sp(comp, 0)} чел.

По ведомствам:
{_table(by_agency, [("agency", "ведомство"), ("drop", "падение"),
                    ("staff_cut", "сокращение штата"),
                    ("competitor", "уход к конкуренту")])}

По регионам:
{_table(by_region, [("region_name", "регион"), ("drop", "падение"),
                    ("staff_cut", "сокращение штата"),
                    ("competitor", "уход к конкуренту")])}

Задача: скажи, какая причина преобладает и где именно. Отдельно назови места, где
преобладает уход к конкуренту, — это зона работы банка, в отличие от сокращения
штата, на которое банк не влияет."""


def competitors(month: str, coverage: float, banks: pd.DataFrame,
                limit: int = 3) -> str:
    """Банки-конкуренты. Ограничение покрытия — часть промпта, а не примечание."""
    return f"""{_RULES.format(limit=limit)}

Сегмент: клиенты бюджетной сферы. Отчётный месяц: {month}.

ВАЖНОЕ ОГРАНИЧЕНИЕ: банк-конкурент известен только по ключевым клиентам, а это
{coverage:.0%} организаций сегмента. По остальным данных нет — их отсутствие не
означает отсутствия конкурентов.

Банки-конкуренты у организаций с оттоком:
{_table(banks, [("bank", "банк"), ("out_kept", "ушло и не вернулось"),
                ("n_org", "организаций")])}

Задача: скажи, что видно по конкурентам, и обязательно оговори ограничение
покрытия."""


def outlook(month: str, horizon: str, months: int, base: float,
            scenarios: pd.DataFrame, season_ok: bool, limit: int = 4) -> str:
    """Прогноз: сохранится численность или восстановится."""
    season = ("сезонность учтена" if season_ok else
              "сезонность НЕ учитывалась: для её оценки не хватило истории")
    return f"""{_RULES.format(limit=limit)}

Сегмент: клиенты бюджетной сферы. Отчётный месяц: {month}.
Горизонт прогноза: до {horizon} ({months} мес.). {season}.

Численность получателей на конец отчётного месяца: {_sp(base, 0)} чел.

Сценарии (отток и приход взяты из истории разными способами):
{_table(scenarios, [("scenario", "сценарий"), ("fl_end", "численность на конец"),
                    ("delta", "изменение"), ("delta_perc", "изменение, доля", "pct")])}

Смысл сценариев: «Сохранение» — отток и приход по среднему за окно;
«Восстановление» — отток по среднему, приход по лучшему месяцу окна;
«Риск» — отток по худшему месяцу окна, приход по среднему.

Задача: скажи, сохранится ли численность до конца года и при каких условиях
возможно восстановление. Это расчёт по истории, а не обещание — не пиши
уверенных утверждений о будущем."""
