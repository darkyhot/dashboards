"""Сегменты. Своя копия словаря — отчёт автономен.

В справочнике ЕПК сегмент записан БОЛЬШИМ именем («Средние», «Рег. госсектор»),
отчётность говорит короткими (КСБ, РГС). Несколько больших сводятся в один
короткий. Неизвестное большое имя НЕ прячется в «прочие»: оно выводится как есть,
иначе новый сегмент справочника тихо растворился бы в чужой строке.
"""
from __future__ import annotations

BIG_TO_SHORT = {
    "Средние": "КСБ", "Крупные": "КСБ", "Крупнейшие": "КСБ",
    "Рег. госсектор": "РГС",
    "Клиенты машиностроения": "СКМ",
    "Фин.институты": "КФИ",
    "SBI": "БМО",
    "Микро": "ММБ", "Малые": "ММБ",
}

FULL = {
    "КСБ": "КСБ · Средние, крупные, крупнейшие",
    "РГС": "РГС · Региональный госсектор",
    "СКМ": "СКМ · Клиенты машиностроения",
    "КФИ": "КФИ · Финансовые институты",
    "БМО": "БМО · SBI",
    "ММБ": "ММБ · Микро и малые",
}

NO_DIM = "Не в справочнике"     # id орг ведомостей нет в справочнике ЕПК
NO_SEG = "Сегмент не указан"    # id орг есть, сегмент пуст

ORDER = ["КСБ", "РГС", "ММБ", "СКМ", "КФИ", "БМО"]
TAIL = [NO_SEG, NO_DIM]

# Заглушки — не имена: обезличиванию и проверке утечки они не подлежат.
PLACEHOLDERS = {NO_DIM, NO_SEG}


def seg_case(col: str = "e.segment_name") -> str:
    """CASE для SQL: большое имя → короткое. Значения — константы кода, не ввод."""
    whens = "\n".join(f"      WHEN '{big}' THEN '{short}'"
                      for big, short in BIG_TO_SHORT.items())
    return (f"CASE {col}\n{whens}\n"
            f"      ELSE COALESCE(NULLIF(btrim({col}), ''), '{NO_SEG}')\n    END")


def ordered(segs) -> list[str]:
    """Порядок строк: основные сегменты, затем неизвестные, затем заглушки."""
    segs = list(dict.fromkeys(s for s in segs if s is not None))
    main = [s for s in ORDER if s in segs]
    other = sorted(s for s in segs if s not in ORDER and s not in TAIL)
    tail = [s for s in TAIL if s in segs]
    return main + other + tail
